"""Write pc2_roms.h: the exact ROM images the simulator ran, for the Arduino programmer."""
import roms, sys
out = sys.argv[1]
imgs = roms.control_images()
disp = roms.display_image()
def arr(name, data):
    lines = [f"const uint8_t {name}[{len(data)}] PROGMEM = {{"]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i+16]) + ",")
    lines.append("};")
    return "\n".join(lines)
with open(out, "w") as f:
    f.write("// Generated by gen_header.py from the PC-2 microcode table. Do not edit by hand.\n")
    f.write("// Control ROM address: A0-A2 step, A3-A6 opcode, A7 zero flag, A8 carry flag (512 bytes).\n")
    f.write("// Display ROM address: A0-A7 value, A8-A9 digit, A10-A11 mode (4096 bytes).\n")
    f.write("// All control lines are active low: a 0 bit means the line is on.\n\n")
    f.write("#include <stdint.h>\n#ifndef PROGMEM\n#define PROGMEM\n#endif\n\n")
    for i in range(3):
        f.write(arr(f"MICROCODE_ROM{i}", imgs[i][:512]) + "\n\n")
    f.write(arr("DISPLAY_ROM", disp[:4096]) + "\n")
print("ok")
